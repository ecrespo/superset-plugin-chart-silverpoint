// SUP-DD-02, H-3 (SUP-T-03, SUP-T-06): from @silverpoint/embed/host-catalog.json (the pinned engine), for every chart a table can
// feed — src/plugins/<slug>/{index,controlPanel,buildQuery}.ts and images/thumbnail{,-dark}.png (the
// demo, drawn by the engine, on the light and on the dark theme) — plus src/catalog.generated.ts, src/components.generated.ts (the lazy
// component map) and src/plugins.generated.ts. `--check` fails when a file differs from a fresh run.
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

interface Role { id: string; prop: string | null; label: string; kind: string; dataType: string; required: boolean; multiple: boolean }
interface Option { name: string; label: string; doc: string; kind: string; values?: string[]; default?: unknown }
interface Chart { slug: string; title: string; family: string; summary: string; binding: string; roles: Role[]; options: Option[]; demo?: { roles: Record<string, string | string[]>; rows: Record<string, unknown>[]; options?: Record<string, unknown> } }

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const pascal = (s: string): string => s.replace(/(^|-)(\w)/g, (_, __, c: string) => c.toUpperCase());
const words = (s: string): string => s.replace(/[-_]+/g, ' ').replace(/(^|\s)\w/g, (c) => c.toUpperCase());
const HEADER = (version: string) => `// Generated by scripts/make-plugins.ts from host catalog ${version}. Do not edit (H-3).\n`;

/** Superset's dark theme as transformProps reads it (SUP-REQ-008): the dark thumbnail is drawn with the
 * appearance hostAppearance picks for it, the default a chart takes on that theme. */
export const DARK_THEME = { background: '#141414', foreground: '#ffffff' } as const;

/** The demo's SVG, drawn by the engine with its stylesheet and EB Garamond inside (no request). */
async function thumbnailSVG(chart: Chart, dark = false): Promise<string> {
  const hosts = await import('@silverpoint/embed/hosts');
  const engine = await import('@silverpoint/embed');
  const { hostAppearance } = await import('@silverpoint/embed/client');
  const demo = chart.demo!;
  const appearance = dark ? (({ ground, substrate }) => ({ ground, substrate }))(hostAppearance({ ...DARK_THEME, highContrast: false })) : undefined;
  const spec = hosts.specFromTable({ chart: chart.slug, table: { rows: demo.rows }, roles: demo.roles, options: { ...(demo.options ?? {}), chrome: 'bare' }, ...(appearance ? { appearance } : {}), size: { width: 400, height: 240 }, id: `thumb-${chart.slug}` });
  if (!spec.ok) throw new Error(`${chart.slug}: the demo does not bind (${JSON.stringify(spec.error)})`);
  const svg = engine.renderToSVG(spec.value, { embedFonts: true });
  if (!svg.ok) throw new Error(`${chart.slug}: the demo does not render`);
  return svg.value.svg;
}

const sha256 = (text: string): string => createHash('sha256').update(text).digest('hex');
/** A thumbnail's key in src/thumbnails.lock.json — `<slug>` or `<slug>:dark` — and its PNG. */
const pngOf = (key: string): string => (key.endsWith(':dark') ? `src/plugins/${key.slice(0, -5)}/images/thumbnail-dark.png` : `src/plugins/${key}/images/thumbnail.png`);

/** PNGs from SVGs in Chromium (CSS custom properties and the embedded face need a browser). Only run
 * when a demo's SVG changed: --check compares the SVGs' digests in src/thumbnails.lock.json. */
async function rasterize(svgs: Map<string, string>): Promise<Map<string, Buffer>> {
  const { chromium } = await import('@playwright/test');
  const browser = await chromium.launch();
  // Reduced motion: the picture is the finished drawing, not a frame of the inking animation.
  const page = await browser.newPage({ viewport: { width: 400, height: 240 }, deviceScaleFactor: 1, reducedMotion: 'reduce' });
  const out = new Map<string, Buffer>();
  for (const [slug, svg] of svgs) {
    // As an image, the SVG is drawn alone, as a file would be: its own stylesheet, nothing of the page's.
    const src = `data:image/svg+xml;base64,${Buffer.from(svg).toString('base64')}`;
    const background = slug.endsWith(':dark') ? DARK_THEME.background : '#fff';
    await page.setContent(`<!doctype html><html><body style="margin:0;background:${background}"><img src="${src}" width="400" height="240"></body></html>`);
    await page.locator('img').evaluate((img: HTMLImageElement) => img.decode());
    await page.waitForTimeout(500); // the stylesheet's 280 ms entrance runs inside an image too
    out.set(slug, await page.locator('img').screenshot());
  }
  await browser.close();
  return out;
}

export async function outputs(): Promise<Map<string, string | Buffer>> {
  return (await generate()).files;
}

async function generate(): Promise<{ files: Map<string, string | Buffer>; svgs: Map<string, string> }> {
  const catalog = JSON.parse(readFileSync(fileURLToPath(import.meta.resolve('@silverpoint/embed/host-catalog.json')), 'utf8'));
  const charts = (catalog.charts as Chart[]).filter((c) => c.binding !== 'none');
  const files = new Map<string, string | Buffer>();
  const svgs = new Map<string, string>();
  const slim = Object.fromEntries(charts.map((c) => [c.slug, { slug: c.slug, title: c.title, family: c.family, summary: c.summary, roles: c.roles, options: c.options }]));
  files.set('src/catalog.generated.ts', [
    HEADER(catalog.version) + "import type { CatalogChart } from './catalog-types.js';",
    '',
    `export const ENGINE_VERSION = ${JSON.stringify(catalog.version)};`,
    `export const APPEARANCE = ${JSON.stringify(catalog.appearance, null, 2)} as const;`,
    `export const CHARTS: Readonly<Record<string, CatalogChart>> = ${JSON.stringify(slim, null, 2)};`,
    '',
  ].join('\n'));
  files.set('src/components.generated.ts', [
    HEADER(catalog.version) + "import type { ComponentType } from 'react';",
    '',
    '/** SUP-REQ-005: each chart\'s @silverpoint/react component, loaded when its plugin first draws. */',
    'export const COMPONENTS: Readonly<Record<string, () => Promise<ComponentType<Record<string, unknown>>>>> = {',
    ...charts.map((c) => `  '${c.slug}': () => import('@silverpoint/react/${c.slug}').then((m) => m.${pascal(c.slug)} as unknown as ComponentType<Record<string, unknown>>),`),
    '};',
    '',
  ].join('\n'));
  files.set('src/plugins.generated.ts', [
    HEADER(catalog.version) + charts.map((c) => `import ${pascal(c.slug)}Plugin from './plugins/${c.slug}/index.js';`).join('\n'),
    '',
    'export const PLUGINS = {',
    ...charts.map((c) => `  '${c.slug}': ${pascal(c.slug)}Plugin,`),
    '} as const;',
    '',
  ].join('\n'));
  for (const chart of charts) {
    const dir = `src/plugins/${chart.slug}`;
    files.set(`${dir}/index.ts`, `${HEADER(catalog.version)}import { CHARTS } from '../../catalog.generated.js';
import { makePlugin } from '../../shared/plugin.js';
import buildQuery from './buildQuery.js';
import controlPanel from './controlPanel.js';
import thumbnail from './images/thumbnail.png';
import thumbnailDark from './images/thumbnail-dark.png';

/** ${chart.title}: ${chart.summary.replace(/\*\//g, '* /')} */
export default makePlugin(CHARTS['${chart.slug}']!, { buildQuery, controlPanel, thumbnail, thumbnailDark });
`);
    files.set(`${dir}/controlPanel.ts`, `${HEADER(catalog.version)}import { CHARTS } from '../../catalog.generated.js';
import { controlPanelFor } from '../../shared/controlPanel.js';

export default controlPanelFor(CHARTS['${chart.slug}']!);
`);
    files.set(`${dir}/buildQuery.ts`, `${HEADER(catalog.version)}import { CHARTS } from '../../catalog.generated.js';
import { buildQueryFor } from '../../shared/buildQuery.js';

export default buildQueryFor(CHARTS['${chart.slug}']!);
`);
    svgs.set(chart.slug, await thumbnailSVG(chart));
    svgs.set(`${chart.slug}:dark`, await thumbnailSVG(chart, true));
  }
  files.set('src/thumbnails.lock.json', `${JSON.stringify(Object.fromEntries([...svgs].map(([slug, svg]) => [slug, sha256(svg)])), null, 2)}\n`);
  return { files, svgs };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { files, svgs } = await generate();
  if (process.argv.includes('--check')) {
    const missing = [...svgs.keys()].filter((key) => { try { return readFileSync(`${ROOT}${pngOf(key)}`).length === 0; } catch { return true; } });
    if (missing.length > 0) { console.log(`missing thumbnails: ${missing.join(', ')}`); process.exit(1); }
    const differs = (path: string, body: string | Buffer) => {
      try { return !readFileSync(`${ROOT}${path}`).equals(Buffer.isBuffer(body) ? body : Buffer.from(body)); } catch { return true; }
    };
    const stale = [...files].filter(([p, b]) => differs(p, b)).map(([p]) => p);
    const extra = readdirSync(`${ROOT}src/plugins`).filter((s) => !files.has(`src/plugins/${s}/index.ts`));
    if (stale.length + extra.length > 0) {
      console.log(`stale: ${[...stale, ...extra].slice(0, 10).join(', ')}${stale.length > 10 ? ', …' : ''} — run \`npm run generate\``);
      process.exit(1);
    }
    console.log(`plugins current (${readdirSync(`${ROOT}src/plugins`).length} charts)`);
  } else {
    let previous: Record<string, string> = {};
    try { previous = JSON.parse(readFileSync(`${ROOT}src/thumbnails.lock.json`, 'utf8')); } catch { /* first run */ }
    const changed = new Map([...svgs].filter(([key, svg]) => previous[key] !== sha256(svg) || !existsSync(`${ROOT}${pngOf(key)}`)));
    const pictures = changed.size > 0 ? await rasterize(changed) : new Map<string, Buffer>();
    for (const key of svgs.keys()) {
      files.set(pngOf(key), pictures.get(key) ?? readFileSync(`${ROOT}${pngOf(key)}`));
    }
    rmSync(`${ROOT}src/plugins`, { recursive: true, force: true });
    for (const [path, body] of files) {
      mkdirSync(`${ROOT}${path.slice(0, path.lastIndexOf('/'))}`, { recursive: true });
      writeFileSync(`${ROOT}${path}`, body);
    }
    console.log(`wrote ${files.size} files (${changed.size} thumbnails drawn)`);
  }
}
export { words };
